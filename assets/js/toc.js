/*
   Post map — builds the right-hand table of contents from the rendered
   headings, then highlights the section currently in view.

   The theme's other TOC (_includes/toc) is generated by kramdown's {:toc} and
   only works from a markdown body. This one runs from the layout, so it reads
   the headings back out of the DOM instead.
   ========================================================================== */

(function () {
  var MIN_HEADINGS = 2;

  function slugify(text) {
    return text
      .toLowerCase()
      .replace(/[^\w\s-]/g, "")
      .trim()
      .replace(/\s+/g, "-");
  }

  function buildMenu(list, headings) {
    var sublist = null;

    headings.forEach(function (heading) {
      var item = document.createElement("li");
      var link = document.createElement("a");

      link.href = "#" + heading.id;
      link.textContent = heading.textContent;
      item.appendChild(link);

      if (heading.tagName === "H3" && list.lastElementChild) {
        // nest under the preceding h2, matching .toc__menu li ul > li a
        if (!sublist) {
          sublist = document.createElement("ul");
          list.lastElementChild.appendChild(sublist);
        }
        sublist.appendChild(item);
      } else {
        sublist = null;
        list.appendChild(item);
      }
    });
  }

  function spy(links) {
    if (!window.IntersectionObserver) {
      return;
    }

    var active = null;

    var observer = new IntersectionObserver(
      function (entries) {
        entries.forEach(function (entry) {
          if (!entry.isIntersecting) {
            return;
          }

          var link = links[entry.target.id];

          if (link && link !== active) {
            if (active) {
              active.classList.remove("active");
            }
            link.classList.add("active");
            active = link;
          }
        });
      },
      // only count a heading as current once it reaches the top of the viewport
      { rootMargin: "-80px 0px -75% 0px" }
    );

    Object.keys(links).forEach(function (id) {
      var heading = document.getElementById(id);
      if (heading) {
        observer.observe(heading);
      }
    });
  }

  function init() {
    var nav = document.querySelector("nav.js-toc");
    var content = document.querySelector(".page__content");

    if (!nav || !content) {
      return;
    }

    var headings = Array.prototype.slice.call(
      content.querySelectorAll("h2, h3")
    );

    // a one-entry post map is noise — drop the whole floated column so it
    // doesn't leave a stray margin next to the text
    if (headings.length < MIN_HEADINGS) {
      var aside = nav.parentNode;
      if (aside) {
        aside.parentNode.removeChild(aside);
      }
      return;
    }

    var links = {};
    var used = {};

    headings.forEach(function (heading) {
      // kramdown auto_ids covers markdown headings; this catches inline HTML ones
      if (!heading.id) {
        var base = slugify(heading.textContent) || "section";
        var id = base;
        var n = 1;

        while (used[id] || document.getElementById(id)) {
          id = base + "-" + n++;
        }
        heading.id = id;
      }
      used[heading.id] = true;
    });

    var list = nav.querySelector(".toc__menu");
    buildMenu(list, headings);

    Array.prototype.forEach.call(list.querySelectorAll("a"), function (link) {
      links[link.getAttribute("href").slice(1)] = link;
    });

    nav.removeAttribute("hidden");
    spy(links);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
